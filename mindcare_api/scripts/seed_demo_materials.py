# ─── Логика ───────────────────────────────────────────────────────────────────

class SeedBlocked(RuntimeError):
    """Окружение не development/test — демо-данные не создаются."""


class SeedConflict(RuntimeError):
    """Совпавший заголовок нельзя безопасно признать demo-материалом."""


@dataclass
class SeedResult:
    created: list = field(default_factory=list)   # slug созданных
    skipped: list = field(default_factory=list)   # slug уже существующих
    adopted: list = field(default_factory=list)   # найдены по заголовку, slug дописан
    author_id: int | None = None


def demo_slug(key: str) -> str:
    return f"{SLUG_PREFIX}{key}"


def ensure_allowed_env() -> None:
    if settings.ENV not in ALLOWED_ENVS:
        raise SeedBlocked(
            "Демо-материалы создаются только при ENV=development или ENV=test."
        )


def _find_author(db):
    """Первая активная учётная запись с ролью admin или supervisor: (id, роль)."""
    users = (
        db.query(User.id)
        .filter(User.deleted_at.is_(None), User.is_active.is_not(False))
        .order_by(User.id)
        .all()
    )
    for (user_id,) in users:
        roles = set(get_active_role_names(db, user_id))
        for role in AUTHOR_ROLES:
            if role in roles:
                return user_id, role
    return None, None


def _matches_demo(article, item, author_id):
    return (
        article.title == item["title"]
        and article.excerpt == item["excerpt"]
        and article.content == item["content"]
        and article.created_by == author_id
        and article.is_published is True
        and article.status == "published"
        and article.published_at is not None
        and article.cover_image is None
        and article.review_comment_enc is None
    )


def _plan(db, author_id):
    """Проверить ВСЕ коллизии до первой записи; soft-deleted не воскрешать."""
    plan = []
    for item in reversed(DEMO_MATERIALS):
        slug = demo_slug(item["key"])
        if db.query(Article.id).filter(Article.slug == slug).first():
            plan.append((item, "skipped", None))
            continue
        candidates = db.query(Article).filter(Article.title == item["title"]).all()
        if candidates:
            if (len(candidates) != 1 or candidates[0].slug is not None
                    or not _matches_demo(candidates[0], item, author_id)):
                raise SeedConflict("demo title collision")
            article = candidates[0]
            action = "skipped" if article.deleted_at is not None else "adopted"
            plan.append((item, action, article.uuid))
        else:
            plan.append((item, "created", None))
    return plan


def _set_slug(article_uuid, item, *, author_id, author_role):
    # create_article владеет своей транзакцией и возвращает UUID, не внутренний id.
    # При сбое этого второго commit остаётся восстанавливаемая статья без slug.
    with SessionLocal() as db:
        article = db.query(Article).filter(
            Article.uuid == UUID(str(article_uuid)),
        ).with_for_update().one()
        if (article.slug is not None or article.deleted_at is not None
                or not _matches_demo(article, item, author_id)):
            raise SeedConflict("demo changed before slug assignment")
        article.slug = demo_slug(item["key"])
        record_event(
            event="article_updated",
            actor=Actor.user(author_id, author_role),
            target=Target("article", article.id),
            outcome=Outcome.SUCCESS,
            metadata={},
            db=db,
        )
        db.commit()


def run(*, dry_run: bool = False) -> SeedResult:
    ensure_allowed_env()
    result = SeedResult()

    # xact-lock живёт в отдельной read-транзакции до конца run, включая commits
    # штатного storage и _set_slug. При ошибке/закрытии соединения освобождается.
    with SessionLocal() as db:
        if not dry_run:
            db.execute(text("SELECT pg_advisory_xact_lock(:key)"), {"key": SEED_LOCK})
        author_id, author_role = _find_author(db)
        category = (
            db.query(Category.id)
            .filter(Category.slug == CATEGORY_SLUG, Category.is_active.is_(True))
            .first()
        )
        category_ids = [category[0]] if category else []
        tag_uuids = {name: str(uuid_) for name, uuid_ in db.query(Tag.name, Tag.uuid).all()}
        plan = _plan(db, author_id)
        if author_id is None and any(action != "skipped" for _, action, _ in plan):
            raise LookupError("no active admin/supervisor account")
        result.author_id = author_id

        now = datetime.now(timezone.utc)
        # Создаём с конца: библиотека сортирует по created_at (новые сначала).
        for index, (item, action, article_uuid) in enumerate(plan):
            slug = demo_slug(item["key"])
            if action == "skipped" or dry_run:
                getattr(result, action).append(slug)
                continue
            if action == "created":
                created = article_storage.create_article(
                    title=item["title"],
                    excerpt=item["excerpt"],
                    content=item["content"],
                    cover_image_uuid=None,
                    category_ids=category_ids,
                    tag_uuids=[tag_uuids[name] for name in item["tags"] if name in tag_uuids],
                    is_published=True,
                    published_at=now - timedelta(days=2 * (len(plan) - 1 - index)),
                    created_by=author_id,
                    actor_role=author_role,
                )
                article_uuid = created["uuid"]
            _set_slug(article_uuid, item, author_id=author_id, author_role=author_role)
            getattr(result, action).append(slug)

    return result


def main() -> int:
    ap = argparse.ArgumentParser(description="Seed demo library materials (idempotent, dev only).")
    ap.add_argument("--dry-run", action="store_true", help="Только проверка, без записи.")
    args = ap.parse_args()

    try:
        result = run(dry_run=args.dry_run)
    except SeedBlocked as exc:
        print(f"[SEED] Заблокировано: {exc}")
        return EXIT_BLOCKED
    except LookupError:
        print("[SEED] Нет активной учётной записи admin/supervisor для атрибуции "
              "демо-материалов - создайте админа (scripts/create_admin.py) и повторите.")
        return EXIT_NO_AUTHOR
    except SeedConflict:
        print("[SEED] Конфликт: совпавший материал нельзя безопасно подхватить. "
              "Проверьте статьи с demo-заголовками вручную.")
        return EXIT_ERROR
    except Exception as exc:
        # Без SQL, credentials, content и свободного текста исключения.
        print(f"[SEED] Ошибка: {type(exc).__name__}", file=sys.stderr)
        return EXIT_ERROR

    prefix = "[SEED][dry-run]" if args.dry_run else "[SEED]"
    verb = "был бы создан" if args.dry_run else "создано"
    print(f"{prefix} Демо-материалов: {verb} {len(result.created)}, "
          f"пропущено (уже есть) {len(result.skipped)}, "
          f"подхвачено по заголовку {len(result.adopted)}.")
    for item in DEMO_MATERIALS:
        slug = demo_slug(item["key"])
        action = next(name for name in ("created", "skipped", "adopted")
                      if slug in getattr(result, name))
        print(f"{prefix} {action}: {slug} | {item['title']}")
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
